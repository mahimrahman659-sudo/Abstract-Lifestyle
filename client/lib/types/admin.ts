import type { OrderDto } from './order';

export type ProductStatus = 'draft' | 'active' | 'archived';

/** Cloudinary-backed image stored on admin products (url + public_id). */
export interface AdminImageAsset {
  url: string;
  publicId: string | null;
}

/** Storefront marketing image slots managed from the admin. */
export type SiteImageKey = 'hero' | 'promo-1' | 'promo-2';

export interface SiteImage {
  key: SiteImageKey;
  image: AdminImageAsset | null;
}

export interface AdminCategory {
  id: string;
  name: string;
  slug: string;
  description?: string;
  image?: string;
  parent: string | null;
  sortOrder: number;
}

export interface AdminProduct {
  id: string;
  name: string;
  slug: string;
  description: string;
  category: string;
  basePrice: number;
  compareAtPrice: number | null;
  images: AdminImageAsset[];
  status: ProductStatus;
  updatedAt: string;
  /** Variant rollup (0 = not purchasable yet). */
  variantCount: number;
  totalStock: number;
}

export interface AdminVariant {
  id: string;
  product: { id: string; name: string; slug: string };
  sku: string;
  size: string | null;
  color: string | null;
  price: number | null;
  compareAtPrice: number | null;
  stock: number;
  lowStockThreshold: number;
  images: string[];
  /** Set when the variant is retired (kept for order history, never sold). */
  archivedAt: string | null;
  inStock: boolean;
  lowStock: boolean;
}

export interface AdminProductDetail {
  product: AdminProduct;
  variants: AdminVariant[];
}

export interface AdminOrderCustomer {
  id: string;
  name: string;
  email: string;
}

export interface AdminOrderDetail {
  order: OrderDto;
  customer: AdminOrderCustomer | null;
}

export interface CreateCategoryPayload {
  name: string;
  parent?: string | null;
  description?: string;
  sortOrder?: number;
}

export interface CreateProductPayload {
  name: string;
  /** Public URL slug. Derived from the name when omitted; renaming never changes it. */
  slug?: string;
  description: string;
  category: string;
  basePrice: number;
  compareAtPrice?: number | null;
  images: AdminImageAsset[];
  status: ProductStatus;
}

export interface VariantPayload {
  sku: string;
  size?: string | null;
  color?: string | null;
  price?: number | null;
  compareAtPrice?: number | null;
  stock: number;
  lowStockThreshold?: number;
  images?: string[];
  /** Stock the form loaded — the server rejects a save if it changed meanwhile. */
  expectedStock?: number;
}

/** One variant per size, with a `PREFIX-SIZE` SKU generated by the server. */
export interface BulkVariantPayload {
  skuPrefix: string;
  color?: string | null;
  price?: number | null;
  compareAtPrice?: number | null;
  lowStockThreshold?: number;
  items: Array<{ size: string; stock: number }>;
  images?: string[];
}

// ---- Customer Activity Center (Phase 2) ---------------------------------

export type ActivityEventType =
  | 'page.view'
  | 'product.view'
  | 'product.impression'
  | 'search.performed'
  | 'filter.applied'
  | 'sort.changed'
  | 'cart.checkout_clicked'
  | 'checkout.viewed'
  | 'auth.login'
  | 'auth.register'
  | 'auth.google_login'
  | 'auth.logout'
  | 'cart.add'
  | 'cart.update'
  | 'cart.remove'
  | 'cart.clear'
  | 'cart.merge'
  | 'checkout.started'
  | 'order.purchased'
  | 'order.cancelled'
  | 'payment.claim_submitted'
  | 'payment.claim_reviewed'
  | 'payment.refunded'
  | 'admin.order_status_changed'
  | 'admin.product_created'
  | 'admin.product_updated'
  | 'admin.product_deleted'
  | 'admin.variant_created'
  | 'admin.variant_updated'
  | 'admin.variant_deleted'
  | 'admin.variant_restored'
  | 'admin.customer_viewed';

export interface ActivityEventDto {
  id: string;
  type: ActivityEventType;
  source: 'client' | 'server';
  ts: string;
  userId?: string;
  anonymousId?: string;
  sessionId?: string;
  path?: string;
  productId?: string;
  variantId?: string;
  orderId?: string;
  customerId?: string;
  query?: string;
  quantity?: number;
  value?: number;
  decision?: string;
  fromStatus?: string;
  toStatus?: string;
}

export interface LiveSessionDto {
  identity: string;
  userId?: string;
  path?: string;
  lastTs: string;
  events: number;
}

export interface LiveActivityDto {
  trackingEnabled: boolean;
  visitors5m: number;
  cartsWithItems: number;
  openCheckouts: number;
  sessions: LiveSessionDto[];
  generatedAt: string;
  stale: boolean;
}

export interface ActivityFeedPage {
  items: ActivityEventDto[];
  page: number;
  limit: number;
  total: number;
  totalPages: number;
}

export interface OrderHistoryEntry {
  order: string;
  orderNumber: string;
  status: string;
  at: string;
  by?: string;
}

export interface CustomerTimelineResult {
  user: { id: string; email: string; name: string; role: string; createdAt: string };
  activity: ActivityFeedPage;
  orderHistory: OrderHistoryEntry[];
  /** True when older status changes were dropped by the server-side cap (L-4). */
  orderHistoryTruncated?: boolean;
  /**
   * Phase 2B-C: false ⇒ behavioral events were NOT collected for this
   * response (tracking disabled); only operational order history is served.
   */
  trackingEnabled: boolean;
}

export interface AdminCustomer {
  id: string;
  email: string;
  name: string;
  role: 'customer' | 'admin';
  createdAt: string;
}

export interface AdminCustomerDetail {
  user: AdminCustomer;
  recentOrders: OrderDto[];
}
